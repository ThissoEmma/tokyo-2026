const tabs = document.querySelector(".day-tabs");
const panel = document.querySelector(".day-panel");

function mapUrl(query) {
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(query)}`;
}

function renderDay(index) {
  const day = days[index];
  document.querySelectorAll(".day-tab").forEach((tab, tabIndex) => {
    tab.setAttribute("aria-selected", String(tabIndex === index));
  });

  panel.innerHTML = `
    <div class="day-header">
      <h3>${day.title}</h3>
      <p class="day-summary">${day.summary}</p>
    </div>
    <div class="day-notes">
      <strong>当天交通与安排</strong>
      <ul>${day.notes.map((note) => `<li>${note}</li>`).join("")}</ul>
    </div>
    <div class="timeline">
      ${day.stops.map((stop) => `
        <article class="stop">
          <time class="stop-time">${stop.time}</time>
          <div>
            <h4>${stop.title}</h4>
            <p class="stop-intro">${stop.intro}</p>
            <details>
              <summary>交通与详细安排</summary>
              <div class="stop-details">
                <p>${stop.detail}</p>
                <p><strong>前往：</strong>${stop.transit}</p>
                <small>${stop.address}</small>
              </div>
            </details>
          </div>
          <a class="stop-map" href="${mapUrl(stop.map)}" target="_blank" rel="noreferrer" aria-label="在 Google Maps 打开 ${stop.title}" title="打开 Google Maps">↗</a>
        </article>
      `).join("")}
    </div>
    <div class="return">
      <strong>${index === days.length - 1 ? "机场安排" : "返程安排"}</strong>
      <p>${day.return}</p>
    </div>
  `;
}

days.forEach((day, index) => {
  const button = document.createElement("button");
  button.className = "day-tab";
  button.type = "button";
  button.role = "tab";
  button.innerHTML = `<strong>${day.date}</strong><span>${day.weekday}</span>`;
  button.setAttribute("aria-selected", String(index === 0));
  button.addEventListener("click", () => renderDay(index));
  tabs.appendChild(button);
});

document.querySelectorAll(".checklist input").forEach((checkbox, index) => {
  const key = `tokyo-check-${index}`;
  checkbox.checked = localStorage.getItem(key) === "true";
  checkbox.addEventListener("change", () => localStorage.setItem(key, checkbox.checked));
});

renderDay(0);
